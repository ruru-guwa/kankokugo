const expandTextMap = (
  groups: Array<[number[], string]>,
): Record<number, string> =>
  Object.fromEntries(
    groups.flatMap(([numbers, text]) => numbers.map((number) => [number, text])),
  );

const combineRole = (
  sectionRole?: string,
  lineRole?: string,
): string | undefined => {
  if (sectionRole && lineRole) {
    return `${sectionRole} ${lineRole}`;
  }

  return sectionRole ?? lineRole;
};

type ExtraGrammarPoint = {
  title: string;
  meaning: string;
  explanation: string;
  example?: string;
  exampleJapanese?: string;
};

const expandGrammarMap = (
  groups: Array<[number[], ExtraGrammarPoint[]]>,
): Record<number, ExtraGrammarPoint[]> =>
  Object.fromEntries(
    groups.flatMap(([numbers, grammarPoints]) =>
      numbers.map((number) => [number, grammarPoints]),
    ),
  );

const expandTokenMeaningMap = (
  groups: Array<[number[], Record<string, string>]>,
): Record<number, Record<string, string>> =>
  Object.fromEntries(
    groups.flatMap(([numbers, meanings]) => numbers.map((number) => [number, meanings])),
  );

