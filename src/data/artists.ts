export function getArtistProfile(
  artist: string,
  artistSongs: Song[],
): ArtistProfile {
  const knownProfile = artistProfiles[artist];
  if (knownProfile) {
    return knownProfile;
  }

  const uniqueTags = Array.from(
    new Set(artistSongs.flatMap((song) => song.tags.filter((tag) => tag !== "中級"))),
  ).slice(0, 5);

  return {
    name: artist,
    lead: `${artist} の曲をアーティスト単位で見られるようにまとめたセクションです。`,
    worldview:
      artistSongs[0]?.overview ??
      `${artist} の曲から見えてくる世界観を、この一覧でまとめて追えるようにしています。`,
    lyricFocus:
      uniqueTags.length > 0
        ? `このアーティストでは ${uniqueTags.join(" / ")} のようなテーマが特によく見えます。`
        : "曲ごとの歌詞解説から、繰り返し出てくるテーマや表現を追いやすくしています。",
    keywords: uniqueTags,
  };
}
